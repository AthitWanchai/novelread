-- Apply to a new Supabase project before enabling cloud mode.
create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  created_at timestamptz not null default now()
);
create table public.books (
  id bigint generated by default as identity primary key,
  owner uuid references public.profiles(id) on delete set null,
  legacy_owner_id bigint,
  title text not null,
  pen_name text not null,
  summary text not null default '',
  category text not null default 'แฟนตาซี',
  tags text not null default '',
  cover text not null default '',
  rating text not null default 'ทั่วไป',
  status text not null default 'กำลังเขียน',
  updated double precision not null default extract(epoch from now())
);
create table public.chapters (
  id bigint generated by default as identity primary key,
  book_id bigint not null references public.books(id) on delete cascade,
  title text not null,
  content text not null default '',
  published boolean not null default false,
  position integer not null default 1,
  updated double precision not null default extract(epoch from now())
);
create table public.shelf (
  user_id uuid not null references auth.users(id) on delete cascade,
  book_id bigint not null references public.books(id) on delete cascade,
  chapter_id bigint,
  progress double precision not null default 0 check (progress between 0 and 1),
  followed boolean not null default false,
  updated double precision not null default extract(epoch from now()),
  anchor jsonb,
  primary key (user_id, book_id)
);
create index books_owner_idx on public.books(owner);
create index books_legacy_owner_idx on public.books(legacy_owner_id);
create index books_updated_idx on public.books(updated desc);
create index chapters_book_position_idx on public.chapters(book_id, position, id);
create index chapters_published_idx on public.chapters(book_id) where published;
create index shelf_user_updated_idx on public.shelf(user_id, updated desc);

alter table public.profiles enable row level security;
alter table public.books enable row level security;
alter table public.chapters enable row level security;
alter table public.shelf enable row level security;
create or replace function public.book_has_published_chapter(book_id bigint) returns boolean
language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.chapters where chapters.book_id = $1 and chapters.published);
$$;
create or replace function public.user_owns_book(book_id bigint) returns boolean
language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.books where books.id = $1 and books.owner = auth.uid());
$$;
revoke all on function public.book_has_published_chapter(bigint), public.user_owns_book(bigint) from public;
grant execute on function public.book_has_published_chapter(bigint), public.user_owns_book(bigint) to anon, authenticated;
create policy "profile owners read" on public.profiles for select to authenticated using (id = auth.uid());
create policy "profile owners update" on public.profiles for update to authenticated using (id = auth.uid()) with check (id = auth.uid());
create policy "published books read" on public.books for select to anon, authenticated using (owner = auth.uid() or public.book_has_published_chapter(id));
create policy "book owners write" on public.books for all to authenticated using (owner = auth.uid()) with check (owner = auth.uid());
create policy "published chapters read" on public.chapters for select to anon, authenticated using (published or public.user_owns_book(book_id));
create policy "chapter owners write" on public.chapters for all to authenticated using (
  public.user_owns_book(book_id)
) with check (public.user_owns_book(book_id));
create policy "shelf owners manage" on public.shelf for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());

create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles(id, name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'name', split_part(coalesce(new.email, ''), '@', 1)))
  on conflict (id) do nothing;
  return new;
end;
$$;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

create or replace function public.setval_for_import(table_name text) returns void
language plpgsql security definer set search_path = '' as $$
begin
  if table_name = 'books' then
    perform setval(pg_get_serial_sequence('public.books', 'id'), greatest(coalesce((select max(id) from public.books), 1), 1), exists(select 1 from public.books));
  elsif table_name = 'chapters' then
    perform setval(pg_get_serial_sequence('public.chapters', 'id'), greatest(coalesce((select max(id) from public.chapters), 1), 1), exists(select 1 from public.chapters));
  else raise exception 'Unsupported table'; end if;
end;
$$;
revoke all on function public.setval_for_import(text) from public, anon, authenticated;
grant execute on function public.setval_for_import(text) to service_role;

